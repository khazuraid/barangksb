export function buildBuiltInLabelTemplate(opts: {
  id: string
  name: string
  layout: string
  fmt: 'qr' | 'code128'
  labelTitle: string
  showName: boolean
  showSKU: boolean
  showLoc: boolean
  showBorder: boolean
  selectedCustomTemplate?: LabelTemplate | null
}): LabelTemplate {
  let widthMm = 64
  let heightMm = 32
  let sheetFormat: SheetFormatId = 'single'

  const dims: Record<string, [number, number, SheetFormatId]> = {
    tj_103: [64, 32, 'tj_103'],
    tj_107: [50, 18, 'tj_107'],
    tj_108: [38, 18, 'tj_108'],
    tj_121: [75, 38, 'tj_121'],
    a4_3x7: [65, 38, 'a4_3x7'],
    a4_4x10: [48, 25.5, 'a4_4x10'],
    label_50x30: [50, 30, 'single'],
    label_40x30: [40, 30, 'single'],
    label_60x40: [60, 40, 'single'],
    label_70x50: [70, 50, 'single'],
    label_100x50: [100, 50, 'single'],
    thermal_58: [58, 40, 'single'],
    thermal_80: [80, 50, 'single'],
  }

  if (dims[opts.layout]) {
    ;[widthMm, heightMm, sheetFormat] = dims[opts.layout]
  } else if (opts.selectedCustomTemplate) {
    widthMm = opts.selectedCustomTemplate.widthMm || 64
    heightMm = opts.selectedCustomTemplate.heightMm || 32
    sheetFormat =
      opts.selectedCustomTemplate.sheetFormat || inferSheetFormat(opts.selectedCustomTemplate)
  }

  if (opts.selectedCustomTemplate) {
    const cloned = JSON.parse(JSON.stringify(opts.selectedCustomTemplate))
    return {
      ...cloned,
      id: opts.id,
      name: opts.name,
      widthMm,
      heightMm,
      sheetFormat,
    }
  }

  const rows: any[] = []
  if (opts.showName) {
    rows.push({
      id: 'r_name',
      type: 'cells',
      field: 'name',
      label: '',
      cells: [{ id: 'c_name', field: 'name', label: '', bold: true, fontSize: 7.5, align: 'left', bgColor: 'white' }],
    })
  }
  if (opts.showSKU) {
    rows.push({
      id: 'r_sku',
      type: 'cells',
      field: 'sku',
      label: '',
      cells: [{ id: 'c_sku', field: 'sku', label: '', bold: true, fontSize: 6.5, align: 'left', bgColor: 'white' }],
    })
  }
  if (opts.showLoc) {
    rows.push({
      id: 'r_loc',
      type: 'cells',
      field: 'location',
      label: '',
      cells: [{ id: 'c_loc', field: 'location', label: '', bold: false, fontSize: 6, align: 'left', bgColor: 'white' }],
    })
  }
  if (rows.length === 0) {
    rows.push({
      id: 'r_name',
      type: 'cells',
      field: 'name',
      label: '',
      cells: [{ id: 'c_name', field: 'name', label: '', bold: true, fontSize: 7, align: 'left', bgColor: 'white' }],
    })
  }

  return {
    id: opts.id,
    name: opts.name,
    widthMm,
    heightMm,
    sheetFormat,
    layoutMode: 'table',
    config: {
      showCutBorder: opts.showBorder,
    },
    tableConfig: {
      borderWidth: opts.showBorder ? 1 : 0,
      borderStyle: 'solid',
      borderColor: '#000000',
      showOuterBorder: opts.showBorder,
      showGridLines: false,
      showColBorder: false,
      showLabelColBorder: false,
      showHeaderBorder: true,
      showFooterBorder: false,
      cellPaddingMm: 0.7,
      labelColWidthPercent: 0,
      showHeader: Boolean(opts.labelTitle.trim()),
      headerText: opts.labelTitle.trim() || 'INVENTARIS KANTOR',
      headerSubText: '',
      headerFontSize: 6,
      headerStyle: 'standard',
      showLogo: false,
      logoUrl: '',
      logoWidthMm: 7,
      qrPosition: 'left',
      qrType: opts.fmt,
      qrWidthMm: Math.max(14, Math.min(24, Math.round(heightMm * 0.7))),
      showFooter: false,
      footerText: '',
      footerFontSize: 5.5,
      defaultFontSize: 6.5,
      rows,
    },
    elements: [],
  }
}
